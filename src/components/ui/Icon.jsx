// Icons are decorative by default. Pair them with visible text for meaning.
export default function Icon({ name, size = 20, strokeWidth = 1.75, ...rest }) {
  const Glyph = icons[name]
  if (!Glyph) return null
  return <Glyph size={size} strokeWidth={strokeWidth} aria-hidden="true" focusable="false" {...rest} />
}
